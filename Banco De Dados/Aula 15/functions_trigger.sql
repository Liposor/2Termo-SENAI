  ID_AUDITORIA INT AUTO_INCREMENT,
  ID_PRODUTO INT NOT NULL,
  PRECO ANTERIRO DECIMAL (10,2),
  PRECO_NOVO DECIMAL(10,2),
  ALTERADO_EM DATETIME DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT PK_ID_AUDITORIA PRIMARY KEY (ID_AUDITORIA),
  CONSTRAINT PK_PRODUTO FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO (ID_PRODUTO)
);

DELIMITER $$

-- EX 2: VALIDAÇÃO AUTOMÁTICA COM SIGNAL

CREATE TRIGGER TAG_PRODUTO_PRECO_UPDATE
AFTER UPDATE ON PRODUTO
FOR EACH NOW 
BEGIN 
  IF OLD.PRECO <> NEW.PRECO THEN
    INSERT INTO AUDIOTIRA_PRECO(ID_PRODUTO, PRECO_ANTERIOR, PRECO_NOVO)
    VALUES (NEW.ID_PRODUTO, OLD.PRECO, NEW.PRECO);
  END IF;
END $$

