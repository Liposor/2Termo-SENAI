-- REGISTRAR AUTOMATICAMENTE AS ALTERAÇÕES DOS PONTOS DE FIDELIDADE DOS CLIENTES.

CREATE TABLE historico_fidelidade (
  ID_HISTORICO INT AUTO_INCREMENT,
  ID_CLIENTE INT NOT NULL,
  PONTOS_ANTERIORES INT,
  PONTOS_NOVOS INT,
  ALTERADO_EM DATETIME DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT PK_ID_HISTORICO PRIMARY KEY (ID_HISTORICO)
);

DELIMITER $$

CREATE TRIGGER TRG_CLIENTE_FIDELIDADE_UPDATE
AFTER UPDATE ON cliente
FOR EACH ROW
BEGIN
  IF OLD.PONTOS_FIDELIDADE <> NEW.PONTOS_FIDELIDADE THEN
    INSERT INTO historico_fidelidade (ID_CLIENTE, PONTOS_ANTERIORES, PONTOS_NOVOS)
    VALUES (NEW.ID_CLIENTE, OLD.PONTOS_FIDELIDADE, NEW.PONTOS_FIDELIDADE);
  END IF;
END $$

DELIMITER ;

START TRANSACTION;

UPDATE cliente
SET PONTOS_FIDELIDADE = PONTOS_FIDELIDADE + 50
WHERE ID_CLIENTE = 1;

SELECT * FROM historico_fidelidade WHERE ID_CLIENTE = 1 ORDER BY ID_HISTORICO DESC;

ROLLBACK;

